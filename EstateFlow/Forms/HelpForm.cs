        private readonly List<(string Title, string Body)> topics = new();

        public HelpForm()
        {
            InitializeComponent();
            KeyDown += (s, e) =>
            {
                if (e.KeyCode == Keys.Escape) btnClose_Click(this, EventArgs.Empty);
            };

            LoadTopicsByRole();
        }

        private void LoadTopicsByRole()
        {
            topics.Clear();
            var user = Session.CurrentUser;

            if (user == null)
            {
                lblHeader.Text = "Руководство пользователя";
                Text = "Руководство пользователя — EstateFlow";
                BuildGuestTopics();
            }
            else if (user.IsClient)
            {
                lblHeader.Text = "Руководство клиента";
                Text = "Руководство клиента — EstateFlow";
                BuildClientTopics();
            }
            else
            {
                lblHeader.Text = user.IsAdmin ? "Руководство администратора" : "Руководство риэлтора";
                Text = $"{lblHeader.Text} — EstateFlow";
                BuildStaffTopics(user.IsAdmin);
            }

            lstTopics.Items.Clear();
            foreach (var (title, _) in topics)
                lstTopics.Items.Add(title);

            if (lstTopics.Items.Count > 0)
                lstTopics.SelectedIndex = 0;
        }

